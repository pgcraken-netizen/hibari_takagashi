export const HATS: Hat[] = (Object.keys(rows) as HatCategory[]).flatMap((cat) =>
  rows[cat].map(([name, emoji, rarity, style, voice, season]) => ({
    id: "",
    name,
    emoji,
    category: cat,
    rarity,
    style,
    voice,
    season,
  })),
).map((h, i) => ({
  ...h,
  id: `hat_${String(i + 1).padStart(3, "0")}`,
  capColor: CAP_COLORS[i % CAP_COLORS.length],
}));

